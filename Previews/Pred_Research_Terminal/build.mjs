import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadArchive } from './data.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const data=loadArchive(path.resolve(here,'../..'));
const payload=JSON.stringify(data).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
const template=fs.readFileSync(path.join(here,'index.template.html'),'utf8');
const css=fs.readFileSync(path.join(here,'style.css'),'utf8');
const js=fs.readFileSync(path.join(here,'app.js'),'utf8')+'\n'+fs.readFileSync(path.join(here,'views.js'),'utf8');
new Function(js);
const html=template.replace('/* STYLES */',()=>css).replace('/* APP_DATA */',()=>payload).replace('/* APP_CODE */',()=>js);
const dist=path.join(here,'dist');
fs.mkdirSync(path.join(dist,'data'),{recursive:true});
fs.writeFileSync(path.join(dist,'index.html'),html);
fs.writeFileSync(path.join(dist,'snapshot.json'),JSON.stringify(data,null,2));
for(const day of data.days)fs.writeFileSync(path.join(dist,'data',day.date+'.json'),JSON.stringify(day,null,2));
console.log(`Dashboard rebuilt: ${data.days.length} archived days; latest ${data.latestDate}; ${data.days.at(-1).matches.length} fixtures. No models executed.`);
